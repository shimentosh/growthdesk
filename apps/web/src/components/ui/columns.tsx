/** A heading's content: the icon, then the word. Works in left- and right-aligned cells. */
export function ColumnLabel({ icon: Icon, children }: { icon?: LucideIcon; children: ReactNode }) {
  if (!Icon) return <>{children}</>;
  return (
    <span className="inline-flex items-center gap-1.5">
      <Icon aria-hidden className="size-3.5 shrink-0 opacity-70" strokeWidth={1.75} />
      {children}
    </span>
  );
}
