/*
 * The built-in library of outreach templates (email, WhatsApp, Telegram and
 * call scripts) that people can copy into their workspace and use in
 * sequences. Bodies are plain text with personalisation tokens; anything in
 * [square brackets] is a placeholder the user fills in before sending.
 *
 * `key` is a stable identifier used to seed workspaces exactly once — never
 * rename or reuse a key. Add new templates with new keys instead.
 */

export type LibraryTemplate = {
  key: string;
  channel: "email" | "whatsapp" | "telegram" | "call";
  name: string;
  category: string;
  description: string;
  subject: string;
  body: string;
};

/** Categories in display order. */
