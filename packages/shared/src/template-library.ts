const lines = (...l: string[]) => l.join("\n");

const email = (key: string, category: string, name: string, description: string, subject: string, body: string): LibraryTemplate => ({
  key,
  channel: "email",
  name,
  category,
  description,
  subject,
  body,
});

const chat = (channel: "whatsapp" | "telegram", key: string, name: string, description: string, body: string): LibraryTemplate => ({
  key,
  channel,
  name,
  category: channel === "whatsapp" ? "WhatsApp" : "Telegram",
  description,
  subject: "",
  body,
});

const call = (key: string, name: string, description: string, body: string): LibraryTemplate => ({
  key,
  channel: "call",
  name,
  category: "Call scripts",
  description,
  subject: "",
  body,
});

